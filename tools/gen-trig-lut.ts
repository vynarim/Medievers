// Build-time generator for src/sim/math/trig-lut.ts (TECH_SPEC §3).
// Float math is allowed here: the output is frozen in the repo and src/sim never computes it.
// Usage: pnpm run gen:lut
import { writeFileSync } from 'node:fs';

export const ANGLE_COUNT = 4096;
export const Q14 = 16384;
export const ATAN_STEPS = 1024;

/** sin in Q14 for each BAM angle; built from one quarter wave so symmetries are exact. */
export function buildSinTable(): number[] {
  const quarter = ANGLE_COUNT / 4;
  const q: number[] = [];
  for (let i = 0; i <= quarter; i++) {
    q.push(Math.round(Math.sin((i * Math.PI) / (2 * quarter)) * Q14));
  }
  const table: number[] = [];
  for (let i = 0; i < ANGLE_COUNT; i++) {
    const quadrant = Math.floor(i / quarter);
    const r = i % quarter;
    const v = quadrant % 2 === 0 ? q[r] : q[quarter - r];
    table.push(quadrant < 2 ? (v as number) : 0 - (v as number)); // 0 - v avoids -0
  }
  return table;
}

/** atan(i / ATAN_STEPS) in BAM for i in 0..ATAN_STEPS, i.e. 0..512 (0..45°). */
export function buildAtanTable(): number[] {
  const table: number[] = [];
  for (let i = 0; i <= ATAN_STEPS; i++) {
    table.push(Math.round((Math.atan(i / ATAN_STEPS) * ANGLE_COUNT) / (2 * Math.PI)));
  }
  return table;
}

function chunk(values: number[], perLine: number): string {
  const lines: string[] = [];
  for (let i = 0; i < values.length; i += perLine) {
    lines.push('  ' + values.slice(i, i + perLine).join(', ') + ',');
  }
  return lines.join('\n');
}

export function renderLutModule(): string {
  return [
    '// GENERATED by tools/gen-trig-lut.ts — do not edit. Regenerate with `pnpm run gen:lut`.',
    '',
    '/** sin(angle) in Q14 (16384 = 1.0) for each BAM angle 0..4095. */',
    'export const SIN_Q14 = Int16Array.from([',
    chunk(buildSinTable(), 16),
    ']);',
    '',
    '/** atan(i / 1024) in BAM for i in 0..1024 (0..512 = 0..45°). */',
    'export const ATAN_BAM = Int16Array.from([',
    chunk(buildAtanTable(), 16),
    ']);',
    '',
  ].join('\n');
}

export const LUT_PATH = new URL('../src/sim/math/trig-lut.ts', import.meta.url);

if (import.meta.main) {
  writeFileSync(LUT_PATH, renderLutModule());
  console.log('wrote src/sim/math/trig-lut.ts');
}
